CREATE TABLE game_spells (
  id INT NOT NULL AUTO_INCREMENT COMMENT '技能目录主键',
  spell_id INT UNSIGNED NULL COMMENT '游戏内技能 ID；允许自定义技能不填写',
  name VARCHAR(128) NOT NULL COMMENT '技能名称',
  source_type VARCHAR(16) NOT NULL COMMENT '技能来源：ENCOUNTER 或 PLAYER',
  class_id INT NULL COMMENT '玩家技能所属职业 ID',
  spec_id INT NULL COMMENT '玩家技能所属专精 ID',
  icon VARCHAR(255) NULL COMMENT '技能图标地址',
  data_source VARCHAR(64) NULL COMMENT '数据来源或维护说明',
  is_active TINYINT(1) NOT NULL DEFAULT 1 COMMENT '是否启用',
  created_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  updated_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (id),
  UNIQUE KEY uk_game_spell_spell_id (spell_id),
  KEY idx_game_spell_catalog (source_type, is_active, name),
  CONSTRAINT chk_game_spell_source_type CHECK (source_type IN ('ENCOUNTER', 'PLAYER'))
) COMMENT='Boss 机制技能和玩家可用技能目录';

CREATE TABLE boss_strategy_tasks (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '战术任务主键',
  version_id BIGINT UNSIGNED NOT NULL COMMENT '所属战术版本',
  task_type_id INT NOT NULL COMMENT '任务类型目录 ID',
  kind VARCHAR(16) NOT NULL COMMENT '任务模式：SEQUENCE 或 TIMELINE',
  order_index SMALLINT NOT NULL DEFAULT 0 COMMENT '展示顺序',
  label VARCHAR(128) NOT NULL COMMENT '任务名称或机制名称',
  encounter_spell_id INT NULL COMMENT '机制技能目录 ID',
  player_spell_id INT NULL COMMENT '执行者玩家技能目录 ID',
  executor_slot_key VARCHAR(64) NOT NULL COMMENT '主要执行者抽象槽位键',
  target_slot_key VARCHAR(64) NULL COMMENT '可选目标抽象槽位键',
  fallback_slot_key VARCHAR(64) NULL COMMENT '后备执行者抽象槽位键',
  notes VARCHAR(1000) NULL COMMENT '任务说明',
  repeat_rule VARCHAR(64) NULL COMMENT '可选重复描述，第一期不解析复杂表达式',
  offset_ms INT UNSIGNED NULL COMMENT '相对战斗开始偏移毫秒',
  window_ms INT UNSIGNED NULL COMMENT '执行时间窗口毫秒',
  phase_label VARCHAR(64) NULL COMMENT '阶段显示名',
  occurrence SMALLINT UNSIGNED NULL COMMENT 'Boss 第几次施法或循环序号',
  reminder_ms INT UNSIGNED NULL COMMENT '提前提醒毫秒数',
  PRIMARY KEY (id),
  KEY idx_boss_strategy_task_order (version_id, kind, order_index),
  KEY idx_boss_strategy_task_type (task_type_id),
  KEY idx_boss_strategy_task_encounter_spell (encounter_spell_id),
  KEY idx_boss_strategy_task_player_spell (player_spell_id),
  CONSTRAINT chk_boss_strategy_task_kind CHECK (kind IN ('SEQUENCE', 'TIMELINE')),
  CONSTRAINT fk_boss_strategy_task_version FOREIGN KEY (version_id) REFERENCES boss_strategy_versions(id) ON DELETE CASCADE ON UPDATE RESTRICT,
  CONSTRAINT fk_boss_strategy_task_type FOREIGN KEY (task_type_id) REFERENCES strategy_task_types(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT fk_boss_strategy_task_encounter_spell FOREIGN KEY (encounter_spell_id) REFERENCES game_spells(id) ON DELETE SET NULL ON UPDATE RESTRICT,
  CONSTRAINT fk_boss_strategy_task_player_spell FOREIGN KEY (player_spell_id) REFERENCES game_spells(id) ON DELETE SET NULL ON UPDATE RESTRICT
) COMMENT='战术版本中的顺序和时间轴任务';

