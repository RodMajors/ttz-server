CREATE TABLE strategy_task_types (
  id INT NOT NULL AUTO_INCREMENT COMMENT '战术任务类型主键',
  code VARCHAR(32) NOT NULL COMMENT '稳定类型编码',
  label VARCHAR(64) NOT NULL COMMENT '类型显示名称',
  is_built_in TINYINT(1) NOT NULL DEFAULT 0 COMMENT '是否系统内置类型，内置项不可删除',
  is_active TINYINT(1) NOT NULL DEFAULT 1 COMMENT '是否启用',
  created_at DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (id),
  UNIQUE KEY uk_strategy_task_type_code (code),
  KEY idx_strategy_task_type_active (is_active, is_built_in)
) COMMENT='战术任务类型目录；允许新增公会自定义类型';

